#!/usr/bin/env python3
"""Render explicit QA settings into a new histogram YAML apply_patch artifact."""
import argparse
import itertools
import math
from pathlib import Path
import yaml


def render(cfg):
    if cfg['schemaVersion'] != 1 or cfg['centBins'] != 9:
        raise ValueError('Unsupported QA histogram schema')
    expected = dict(representations=['4He', '3He', '3HeAs4He'],
                    massSuffixes=['', '_SBPos', '_SBNeg', '_signalLow', '_signalHigh'],
                    stagePrefixes=['', 'PrePid'], mixingPrefixes=['', 'Mixed_'])
    for key, value in expected.items():
        if cfg[key] != value:
            raise ValueError('Category mapping differs from the C++ contract: ' + key)
    axes = cfg['axes']
    if set(axes) != {'Kstar', 'NSigma', 'POverQ'}:
        raise ValueError('Explicit three numeric QA axes required')
    for axis in axes.values():
        if axis['nBins'] <= 0 or not all(math.isfinite(axis[k]) for k in ('min', 'max')) or axis['max'] <= axis['min']:
            raise ValueError('Invalid numeric QA axis')
    histograms = {}
    for stage, mode, representation, suffix, cent, observable in itertools.product(
            cfg['stagePrefixes'], cfg['mixingPrefixes'], cfg['representations'],
            cfg['massSuffixes'], range(cfg['centBins']), ('NSigma', 'POverQ')):
        key = 'hKstar' + observable + stage + '_' + mode + representation + suffix + '_CentBin' + str(cent)
        source = '4He' if representation == '4He' else '3He'
        stage_label = 'prePID' if stage else 'selected'
        ytitle = 'n#sigma_{' + source + '}' if observable == 'NSigma' else 'raw |p/q| [GeV/c]'
        title = '{} {} {} {} cent9={};k* [GeV/c];{}'.format(
            stage_label, 'ME' if mode else 'SE', representation, suffix or 'signal', cent, ytitle)
        if key in histograms:
            raise ValueError('Duplicate QA histogram key')
        histograms[key] = dict(type='TH2D', title=title, xAxis=axes['Kstar'], yAxis=axes[observable])
    if len(histograms) != 1080:
        raise ValueError('Incomplete dense QA contract')
    titles = dict(Kstar='k* [GeV/c]', POverQ='raw |p/q| [GeV/c]', NSigma='source-nucleus nSigma')
    joint_axes = {name: dict(bins=axes[name]['nBins'], min=axes[name]['min'], max=axes[name]['max'], title=titles[name])
                  for name in ('Kstar', 'POverQ', 'NSigma')}
    categories = cfg['jointCategoryAxes']
    if list(categories) != ['Cent9', 'Representation', 'MixingMode', 'MassClass', 'PidStage']:
        raise ValueError('Joint categorical axis order differs from C++ schema')
    for name, size in zip(categories, (9, 3, 2, 4, 2)):
        axis = categories[name]
        if axis['bins'] != size or axis['min'] != -.5 or axis['max'] != size - .5:
            raise ValueError('Joint categorical axis extent mismatch')
        joint_axes[name] = axis
    result = dict(axes=axes, histograms=histograms,
                  jointSparse=dict(schemaVersion=1, name='hNuclearPidPairJoint',
                                   title='Nuclear PID pair joint raw counts', axes=joint_axes))
    return '# Generated by script/generate_femto_nuclear_pid_pair_qa_hist.py; edit explicit tools settings, then regenerate.\n' + yaml.safe_dump(result, sort_keys=False, allow_unicode=True)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--settings', required=True, type=Path)
    parser.add_argument('--output', required=True, type=Path)
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument('--patch-file', type=Path)
    mode.add_argument('--check', action='store_true')
    args = parser.parse_args()
    project = Path(__file__).resolve().parents[1]
    text = render(yaml.safe_load(args.settings.read_text()))
    output = args.output.resolve()
    if args.check:
        if output.read_text() != text:
            raise ValueError('Generated histogram YAML differs from explicit settings')
        print('NUCLEAR_PID_PAIR_HIST_CHECK_PASS 1080 TH2D + 8D joint')
    else:
        if output.exists():
            raise ValueError('Refusing to replace an existing histogram YAML')
        relative = output.relative_to(project)
        if relative.parts[:2] != ('config', 'hist'):
            raise ValueError('Histogram output must be under project config/hist')
        patch = '*** Begin Patch\n*** Add File: star-analyzer/' + str(relative) + '\n'
        patch += ''.join('+' + line + '\n' for line in text.splitlines()) + '*** End Patch\n'
        args.patch_file.parent.mkdir(parents=True, exist_ok=True)
        with args.patch_file.open('x') as stream:
            stream.write(patch)
        print('APPLY_PATCH_ARTIFACT', args.patch_file)


if __name__ == '__main__':
    main()
