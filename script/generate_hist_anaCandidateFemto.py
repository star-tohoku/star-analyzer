#!/usr/bin/env python3
"""Generate the HistManager YAML for StCandidateFemtoMaker from its candidateFemto YAML.

Usage:
  script/generate_hist_anaCandidateFemto.py <candidateFemto.yaml> <kf-source hist YAML or ""> <output.yaml>

Every QA histogram name the Maker fills (see StMaker/StCandidateFemtoMaker/StCandidateFemtoMaker.cxx)
is declared here per species / channel / daughter combination. The reconstruction-part QA histograms
of KfParticleCandidateSource and OfficialEventSelection (hKf*, hXi_*, hK0short_*, ...) are copied from
the given kf-source hist YAML (its axes block and histograms, without hN / hVz / hRefMult /
hKfTrackCovCount). The Xi QA histograms of that YAML mix both charges (other Makers fill them so); they are
declared here once per charge (XI_QA_PER_CHARGE: hXiMinus_<suffix>, hXiPlus_<suffix>), as
KfParticleCandidateSource fills them. The pair histograms (THnSparse) are booked by the Maker itself, not here.
"""
import sys

# Final-state track names per source particle key (CandidateSource::DaughterNames).
DAUGHTERS = {
    "xi_minus_kf": ["proton", "pion", "bachelor"],
    "xi_plus_kf": ["proton", "pion", "bachelor"],
    "k0s_kf": ["pionPlus", "pionMinus"],
}
TRACK_DAUGHTERS = ["track"]

# Charge-mixed Xi QA histogram of the kf-source YAML -> suffix of the per-charge histograms.
XI_QA_PER_CHARGE = {
    "hXi_InvMass": "InvMass", "hXi_InvMass_vs_Cent9": "InvMass_vs_Cent9", "hXi_InvMass_vs_Pt": "InvMass_vs_Pt",
    "hXi_InvMass_vs_DecayLength": "InvMass_vs_DecayLength", "hXi_InvMass_vs_Y": "InvMass_vs_Y",
    "hXi_Pt": "Pt", "hXi_Eta": "Eta", "hDCA12": "DCA12", "hDCAV0": "DCAV0", "hCosPointing": "CosPointing",
    "hKfChi2Ndf": "Chi2Ndf", "hKfTopoChi2Ndf": "TopoChi2Ndf", "hKfTopoChi2NdfRaw": "TopoChi2NdfRaw",
    "hKfDecayLengthSignificance": "DecayLengthSignificance", "hKfLambdaMassFromXi": "LambdaMassRaw",
    "hKfLambdaMassFromXiSelected": "LambdaMassSelected",
}


def read_flat(path):
    values = {}
    with open(path) as f:
        for line in f:
            line = line.split("#", 1)[0].strip()
            if not line or ":" not in line:
                continue
            k, v = line.split(":", 1)
            values[k.strip()] = v.strip()
    return values


def axis(n, lo, hi):
    return "{nBins: %d, min: %s, max: %s}" % (n, repr(lo), repr(hi))


def main():
    if len(sys.argv) != 4:
        sys.exit(__doc__)
    femto_path, kf_hist_path, out_path = sys.argv[1:]
    cfg = read_flat(femto_path)
    species = [s.strip() for s in cfg["speciesKeys"].split(",")]
    mass_axis = {}
    daughters = {}
    for s in species:
        n, lo, hi = [x.strip() for x in cfg["species_%s_massAxis" % s].split(",")]
        mass_axis[s] = (int(n), float(lo), float(hi))
        daughters[s] = DAUGHTERS.get(cfg["species_%s_particleKey" % s], TRACK_DAUGHTERS)
    channels = []
    for i in range(int(cfg["nChannels"])):
        channels.append((cfg["channel_%d_name" % i], cfg["channel_%d_partA" % i], cfg["channel_%d_partB" % i]))

    out = ["# GENERATED by script/generate_hist_anaCandidateFemto.py from %s" % femto_path,
           "# and %s -- edit the generator or its inputs, not this file." % (kf_hist_path or "(no kf-source hist YAML)")]
    hist = []
    if kf_hist_path:
        with open(kf_hist_path) as f:
            lines = f.read().split("\n")
        start = lines.index("histograms:")
        out += [l for l in lines[:start] if not l.startswith("#")]
        skip = {"hN", "hVz", "hRefMult", "hKfTrackCovCount"}
        blocks = []  # (name, lines)
        for l in lines[start + 1:]:
            if l.startswith("#"):
                continue
            if l.startswith("  h") and l.rstrip().endswith(":"):
                blocks.append((l.strip()[:-1], []))
            if blocks:
                blocks[-1][1].append(l.rstrip())
        for name, block in blocks:
            if name in skip:
                continue
            if name not in XI_QA_PER_CHARGE:
                hist.extend(block)
                continue
            for prefix, label in (("hXiMinus_", "Xi-"), ("hXiPlus_", "Xi+")):
                for l in block:
                    if l.strip() == name + ":":
                        hist.append("  %s%s:" % (prefix, XI_QA_PER_CHARGE[name]))
                    elif l.strip().startswith('title: "'):
                        hist.append(l.replace('title: "', 'title: "%s: ' % label, 1))
                    else:
                        hist.append(l)
        missing = set(XI_QA_PER_CHARGE) - set(n for n, _ in blocks)
        if missing:
            sys.exit("kf-source hist YAML lacks %s" % sorted(missing))
    else:
        out.append("axes: {}")

    def h1(name, ax, title):
        hist.extend(["  %s:" % name, "    axis: %s" % ax, '    title: "%s"' % title])

    def h2(name, ax, ay, title):
        hist.extend(["  %s:" % name, "    xAxis: %s" % ax, "    yAxis: %s" % ay, '    title: "%s"' % title])

    def h3(name, ax, ay, az, title):
        hist.extend(["  %s:" % name, "    xAxis: %s" % ax, "    yAxis: %s" % ay, "    zAxis: %s" % az,
                     '    title: "%s"' % title])

    count = axis(1, -0.5, 0.5)
    kstar = axis(200, 0.0, 2.0)
    cent9 = axis(9, -0.5, 8.5)
    h1("hN", count, "Accepted events;;Counts")
    h1("hVz", axis(100, 195.0, 205.0), "Primary vertex z (all read events);V_{z} [cm];Counts")
    h2("hEvtQA_MultVsNTof_all", axis(80, 0.0, 400.0), axis(60, 0.0, 300.0), "accepted events;fxtMult;nBTofMatch")
    for c in range(9):
        h2("hTrackQA_dEdxVsQP_cent%d" % c, axis(600, -4.0, 8.0), axis(400, 0.0, 80.0),
           "all tracks, cent9 %d;q|p| (global) [GeV/c];dE/dx [keV/cm]" % c)
        h2("hTrackQA_m2VsQP_cent%d" % c, axis(600, -4.0, 8.0), axis(250, -0.2, 9.8),
           "all TOF tracks, cent9 %d;q|p| (global) [GeV/c];m^{2} [GeV^{2}/c^{4}]" % c)
    for s in species:
        n, lo, hi = mass_axis[s]
        m = axis(n, lo, hi)
        h1("hCandidateMass_%s" % s, m, "%s candidates (every usable candidate);mass variable;Counts" % s)
        h2("hCandidateMassVsP_%s" % s, axis(100, 0.0, 4.0), m, "%s candidates;|p| [GeV/c];mass variable" % s)
        h1("hCandidateScore_%s" % s, axis(200, -1.0, 1.0), "%s BDT score;score;Counts" % s)
        h2("hCandidateScoreVsMass_%s" % s, m, axis(100, -1.0, 1.0), "%s;mass variable;BDT score" % s)
        h2("hCandidateMassVsCent9_%s" % s, m, axis(9, -0.5, 8.5), "%s candidates (usable);mass variable;cent9" % s)
        h3("hCandidateMassVsCent9VsScore_%s" % s, m, axis(9, -0.5, 8.5), axis(200, -1.0, 1.0),
           "%s candidates (BDT);mass variable;cent9;BDT score" % s)
        h2("hCandidatePtVsYLab_%s_signal" % s, axis(200, -5.0, 5.0), axis(200, 0.0, 10.0),
           "%s (signal window);y_{lab};p_{T} [GeV/c]" % s)
        h2("hCandidatePtVsYCm_%s_signal" % s, axis(100, -2.5, 2.5), axis(100, 0.0, 3.0),
           "%s (signal window);y_{cm};p_{T} [GeV/c]" % s)
        for d in daughters[s]:
            h1("hDaughterEtaLab_%s_%s_signal" % (s, d), axis(120, -3.0, 1.0), "%s %s (signal);#eta_{lab};Counts" % (s, d))
            h2("hDaughterPtVsYLab_%s_%s_signal" % (s, d), axis(200, -5.0, 5.0), axis(200, 0.0, 10.0),
               "%s %s (signal);y_{lab};p_{T} [GeV/c]" % (s, d))
    for name, a, b in channels:
        ma, mb = axis(*mass_axis[a]), axis(*mass_axis[b])
        nA, nB = len(daughters[a]), len(daughters[b])
        # Purity inputs of the CF macros: the candidates that enter this channel's pairs (after the channel's
        # shared-track rule, events with both species).
        for s, ms in ((a, ma), (b, mb)):
            h2("hChannelMassVsCent9_%s_%s" % (name, s), ms, cent9,
               "%s candidates of channel %s (events with both species);mass variable;cent9" % (s, name))
            h3("hChannelMassVsCent9VsScore_%s_%s" % (name, s), ms, cent9, axis(200, -1.0, 1.0),
               "%s candidates of channel %s (events with both species, BDT);mass variable;cent9;BDT score" % (s, name))
            h1("hChannelSharedTrackRemovedMass_%s_%s" % (name, s), ms,
               "%s candidates removed by the shared-track rule of channel %s;mass variable;Counts" % (s, name))
        for tag in ("SE", "ME"):
            h1("hKstar%s_%s" % (tag, name), kstar, "%s %s (signal x signal);k* [GeV/c];Counts" % (tag, name))
            h2("hKstar%sVsCent_%s" % (tag, name), kstar, cent9, "%s %s (signal x signal);k* [GeV/c];cent9" % (tag, name))
            h2("hPairYCmVsKstar%s_%s" % (tag, name), kstar, axis(60, -1.5, 1.5),
               "%s %s (signal x signal);k* [GeV/c];pair y_{cm}" % (tag, name))
            h2("hPairMtVsKstar%s_%s" % (tag, name), kstar, axis(80, 0.5, 2.5),
               "%s %s (signal x signal);k* [GeV/c];m_{T} [GeV/c^{2}]" % (tag, name))
            for da in daughters[a]:
                for db in daughters[b]:
                    h3("hDEtaDPhiStar%s_%s_%s_%s" % (tag, name, da, db), axis(80, -0.2, 0.2), axis(80, -0.2, 0.2),
                       axis(4, 0.0, 1.0), "%s %s %s-%s (signal x signal);#Delta#phi*_{min};#Delta#eta;k* [GeV/c]"
                       % (tag, name, da, db))
            h3("hDaughterMinDist%s_%s" % (tag, name), axis(50, 0.0, 0.25), ma, axis(10, 0.0, 1.0),
               "%s %s (%s signal): min same-charge daughter distance;#sqrt{#Delta#eta^{2}+#Delta#phi^{2}};mass %s;k* [GeV/c]"
               % (tag, name, b, a))
            h2("hDaughterMinDistVsDPt%s_%s" % (tag, name), axis(50, 0.0, 0.25), axis(40, -1.0, 1.0),
               "%s %s (k*<0.5);min daughter distance;relative #Delta p_{T}" % (tag, name))
            h3("hDecayVertexDistance%s_%s" % (tag, name), axis(50, 0.0, 25.0), ma, axis(10, 0.0, 1.0),
               "%s %s (%s signal): decay-vertex distance;d_{vtx} [cm];mass %s;k* [GeV/c]" % (tag, name, b, a))
            h3("hDecayLengthA%s_%s" % (tag, name), axis(50, 0.0, 25.0), ma, axis(10, 0.0, 1.0),
               "%s %s (%s signal): %s decay length;L [cm];mass %s;k* [GeV/c]" % (tag, name, b, a, a))
        h2("hDecayVertexVsDecayLengthA_%s" % name, axis(50, 0.0, 25.0), axis(50, 0.0, 25.0),
           "SE %s;|r_{A}-PV| [cm];decay length A [cm]" % name)
        h1("hShareRejectSE_%s" % name, axis(nA * nB, -0.5, nA * nB - 0.5),
           "SE pairs sharing a track (both outside the signal windows);daughter combination (iA*nB+iB);Counts")
        h1("hKstarShareRejectSE_%s" % name, kstar, "SE pairs sharing a track (both outside the signal windows);k* [GeV/c];Counts")
        h2("hEvtQA_NAVsNB_%s" % name, axis(41, -0.5, 40.5), axis(5, -0.5, 4.5),
           "%s;N(%s) (clamped);N(%s) (clamped)" % (name, a, b))
        h2("hEvtQA_MultVsNTof_%s_withB" % name, axis(80, 0.0, 400.0), axis(60, 0.0, 300.0),
           "events with a %s;fxtMult;nBTofMatch" % b)
        h2("hEvtQA_MassAVsNB_%s" % name, ma, axis(4, -0.5, 3.5), "%s;mass %s;N(%s) (clamped)" % (name, a, b))
        for sel in ("all", "withB"):
            h2("hEvtQA_MassAVsMult_%s_%s" % (name, sel), ma, axis(100, 0, 400), "%s (%s);mass %s;fxtMult" % (name, sel, a))
            h2("hEvtQA_MassAVsNTof_%s_%s" % (name, sel), ma, axis(100, 0, 400), "%s (%s);mass %s;nBTofMatch" % (name, sel, a))
            h2("hEvtQA_MassAVsVr_%s_%s" % (name, sel), ma, axis(20, 0.0, 2.0), "%s (%s);mass %s;V_{r} [cm]" % (name, sel, a))
        h2("hEvtQA_MassBVsNA_%s" % name, mb, axis(41, -0.5, 40.5), "%s;mass %s;N(%s) (clamped)" % (name, b, a))
        h2("hEvtQA_MassBVsMult_%s" % name, mb, axis(100, 0, 400), "%s;mass %s;fxtMult" % (name, b))

    out.append("")
    out.append("histograms:")
    out += hist
    with open(out_path, "w") as f:
        f.write("\n".join(out) + "\n")
    print("wrote %s" % out_path)


if __name__ == "__main__":
    main()
